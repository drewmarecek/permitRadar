"""Async Playwright scraper.

Responsibilities
  * Open a managed browser (one per `Scraper` instance).
  * Decide HTML vs PDF based on URL extension and HTTP `Content-Type`.
  * For HTML: navigate, wait for network idle, strip boilerplate, return
    cleaned text + raw HTML.
  * For PDFs: download via Playwright's `APIRequestContext` (carries the
    browser's cookies/UA) and extract text with `pypdf`.
  * Apply a hard char cap so a 10MB page can't blow up our token budget.

We deliberately surface a simple `FetchResult` dataclass to the rest of
the pipeline so `extractor.py` doesn't need to know about Playwright.
"""

